"use client";
import { useEffect, useState } from "react";
import { supabaseBrowser } from "../../../lib/supabase-browser";

type Factor = { id: string; status: string; friendly_name?: string | null };

export default function MfaPanel({ next }: { next: string }) {
  const [factors, setFactors] = useState<Factor[]>([]);
  const [aal, setAal] = useState<string>("aal1");
  const [enroll, setEnroll] = useState<{ id: string; qr: string; secret: string } | null>(null);
  const [code, setCode] = useState("");
  const [msg, setMsg] = useState<{ kind: "ok" | "err"; text: string } | null>(null);
  const [busy, setBusy] = useState(false);

  async function refresh() {
    const sb = supabaseBrowser();
    const [{ data: f }, { data: a }] = await Promise.all([sb.auth.mfa.listFactors(), sb.auth.mfa.getAuthenticatorAssuranceLevel()]);
    setFactors((f?.totp ?? []) as Factor[]);
    setAal(a?.currentLevel ?? "aal1");
  }
  useEffect(() => { refresh().catch(() => setMsg({ kind: "err", text: "Could not load your security settings." })); }, []);

  const verified = factors.find((f) => f.status === "verified");

  async function start() {
    setBusy(true); setMsg(null);
    // Clear any half-finished enrollment first so the user is never stuck.
    const sb = supabaseBrowser();
    for (const f of factors.filter((f) => f.status !== "verified")) await sb.auth.mfa.unenroll({ factorId: f.id });
    const { data, error } = await sb.auth.mfa.enroll({ factorType: "totp", friendlyName: `IndicoRica ${new Date().toISOString().slice(0, 10)}` });
    setBusy(false);
    if (error || !data) return setMsg({ kind: "err", text: "Could not start enrollment. Please try again." });
    setEnroll({ id: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
  }

  async function confirm(factorId: string) {
    setBusy(true); setMsg(null);
    const { error } = await supabaseBrowser().auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setBusy(false);
    if (error) return setMsg({ kind: "err", text: "That code was not accepted. Wait for the next code and try again." });
    setCode(""); setEnroll(null);
    setMsg({ kind: "ok", text: "Two-factor sign-in is active for this session." });
    await refresh();
    window.location.assign(next);
  }

  return (
    <div className="mt-6 space-y-5">
      {verified ? (
        <div className="space-y-3">
          <p className="rounded bg-green-50 p-3 text-sm text-green-800">
            Authenticator app is set up. This session is {aal === "aal2" ? "verified" : "NOT yet verified — enter a code below"}.
          </p>
          {aal !== "aal2" && <CodeBox code={code} setCode={setCode} busy={busy} onSubmit={() => confirm(verified.id)} label="Verify this session" />}
          <p className="text-xs text-stone-500">
            Lost your phone? There are no recovery codes. A super admin (or the site owner in the Supabase dashboard:
            Authentication → Users → the user → remove factor) can reset it. Save a backup of your secret in a password manager when enrolling.
          </p>
        </div>
      ) : enroll ? (
        <div className="space-y-3">
          <p className="text-sm">1. Scan this QR code with your authenticator app.</p>
          {/* qr_code is an SVG data URI generated by Supabase */}
          <img src={enroll.qr} alt="QR code for your authenticator app" width={180} height={180} className="rounded border" />
          <p className="text-sm">Can’t scan? Enter this key manually and keep a copy in your password manager:</p>
          <code className="block break-all rounded bg-stone-100 p-2 text-xs">{enroll.secret}</code>
          <p className="text-sm">2. Enter the 6-digit code shown in the app.</p>
          <CodeBox code={code} setCode={setCode} busy={busy} onSubmit={() => confirm(enroll.id)} label="Turn on two-factor sign-in" />
        </div>
      ) : (
        <button onClick={start} disabled={busy} className="rounded bg-orange-700 px-4 py-3 text-white hover:bg-orange-800 disabled:opacity-60">
          Set up authenticator app
        </button>
      )}
      {msg && <p role={msg.kind === "err" ? "alert" : "status"} className={`rounded p-3 text-sm ${msg.kind === "err" ? "bg-red-50 text-red-800" : "bg-green-50 text-green-800"}`}>{msg.text}</p>}
    </div>
  );
}

function CodeBox({ code, setCode, busy, onSubmit, label }: { code: string; setCode: (v: string) => void; busy: boolean; onSubmit: () => void; label: string }) {
  return (
    <form onSubmit={(e) => { e.preventDefault(); onSubmit(); }} className="flex gap-2">
      <label htmlFor="otp" className="sr-only">6-digit code</label>
      <input id="otp" inputMode="numeric" autoComplete="one-time-code" pattern="[0-9]{6}" maxLength={6} value={code}
        onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))} className="w-32 rounded border border-stone-300 px-3 py-2 tracking-widest" placeholder="123456" />
      <button disabled={busy || code.length !== 6} className="rounded bg-stone-800 px-4 py-2 text-white disabled:opacity-60">{label}</button>
    </form>
  );
}
